"""Tables of the "s" edition (docs/s/README.md).

A metadata of their own, so upstream's autogenerated migrations never see
them, and a migration chain of their own (``migrations_s``, version table
``alembic_version_s``), so upstream's numbering never collides with it.
Foreign keys to upstream tables live in the migrations, not here: a separate
metadata cannot resolve them.
"""

from datetime import datetime
from typing import Optional

from sqlalchemy import BigInteger, DateTime, Integer, String, func
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column


class SBase(DeclarativeBase):
    pass


class SUserBlock(SBase):
    __tablename__ = "s_user_blocks"

    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[int] = mapped_column(Integer, unique=True, index=True)
    telegram_id: Mapped[Optional[int]] = mapped_column(BigInteger, nullable=True)
    reason: Mapped[str] = mapped_column(String(512), default="")
    # None: until lifted by hand.
    until: Mapped[Optional[datetime]] = mapped_column(DateTime(timezone=True), nullable=True)
    created_by: Mapped[Optional[int]] = mapped_column(BigInteger, nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), server_default=func.now())
